"""Copy the shared cart tuning into the mobile web game.

The source of truth is shopping-cart/tuning/cart_tuning.json (the Godot game reads it directly).
The web page can't fetch files when hosted as an artifact, so this writes mobile/cart_tuning.js:
    python3 tools/sync_tuning.py
"""
import json, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(REPO, "shopping-cart", "tuning", "cart_tuning.json")
out = os.path.join(REPO, "mobile", "cart_tuning.js")
data = json.load(open(src))
with open(out, "w") as f:
    f.write("// Generated by tools/sync_tuning.py from shopping-cart/tuning/cart_tuning.json. Edit that file, not this one.\n")
    f.write("window.CART_TUNING = " + json.dumps(data, indent=2) + ";\n")
print("TUNING", out)
